export function getZodiacByDate(month: number, day: number): ZodiacSign {
  const boundaries: [number, number, ZodiacSign][] = [
    [3, 21, '白羊座'], [4, 20, '金牛座'], [5, 21, '双子座'],
    [6, 22, '巨蟹座'], [7, 23, '狮子座'], [8, 23, '处女座'],
    [9, 23, '天秤座'], [10, 24, '天蝎座'], [11, 23, '射手座'],
    [12, 22, '摩羯座'], [1, 20, '水瓶座'], [2, 19, '双鱼座']
  ]

  for (let i = boundaries.length - 1; i >= 0; i--) {
    const [m, d, sign] = boundaries[i]
    if (month > m || (month === m && day >= d)) {
      return sign
    }
  }
  return '白羊座'
}

export function getZodiacInfo(name: ZodiacSign): ZodiacInfo | undefined {
  return ZODIAC_LIST.find(z => z.name === name)
}

